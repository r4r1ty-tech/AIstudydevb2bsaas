package quizsolver

import "testing"

// Условия взяты дословно из реальных тестов Moodle (тема Adaptable).
const (
	qLZ78Decode = "Декодировать сообщение, сжатое алгоритмом LZ78: [0к] [0о] [0с] [0т] [0ь] [0_] [1о] [3а] [6о] [8_] [2к] [0о] Словарь - 10 символов. Запишите ответ строчными русскими буквами."
	qLZ77Encode = "Сжать сообщение методом LZ77: СКЛАД_КЛАД_КЛАДЕЗЬ Размер словаря - 10 символов, размер буфера - 6 символов. Запишите ответ заглавными русскими буквами и цифрами без пробелов между кодами. Формат одной записи: <число,число,буква> Пример кода: <0,0,С><0,0,Т><0,0,О><0,0,Л><0,0,_><5,2,О>"
	qLZSSEncode = "Сжать сообщение методом LZSS: КУСКУС_УКУС_КУСОК Размер словаря - 10 символов, размер буфера - 6 символов. Запишите ответ заглавными русскими буквами и цифрами, без пробелов между записями. Формат одной записи: [число'буква'] или [число<число,число>] Пример кода: [0'С'] [0'Т'] [0'О'] [0'Л'] [0'_'] [1<5,3>]"
	qHuffman    = "Декодировать сообщение, сжатое адаптивным методом Хаффмана: 'R'0'T'01100'N'010111100'D'1001 Запишите ответ заглавными латинскими буквами без пробелов и разделителей между символами."
)

func TestSolveLZ78DecodeRealQuestion(t *testing.T) {
	res, ok := Solve(qLZ78Decode)
	if !ok {
		t.Fatal("решатель не взял реальное условие LZ78")
	}
	if res.Answer != "кость_коса_оса_око" {
		t.Fatalf("ответ = %q, ждали %q", res.Answer, "кость_коса_оса_око")
	}
}

func TestSolveLZ77EncodeRoundTrip(t *testing.T) {
	res, ok := Solve(qLZ77Encode)
	if !ok {
		t.Fatal("решатель не взял условие LZ77")
	}
	msg, ok := DecodeLZ77(res.Answer, 10, 6)
	if !ok || msg != "СКЛАД_КЛАД_КЛАДЕЗЬ" {
		t.Fatalf("обратное декодирование %q дало %q (ok=%t)", res.Answer, msg, ok)
	}
}

func TestSolveLZSSEncodeRoundTrip(t *testing.T) {
	res, ok := Solve(qLZSSEncode)
	if !ok {
		t.Fatal("решатель не взял условие LZSS")
	}
	msg, ok := DecodeLZSS(res.Answer, 10, 6)
	if !ok || msg != "КУСКУС_УКУС_КУСОК" {
		t.Fatalf("обратное декодирование %q дало %q (ok=%t)", res.Answer, msg, ok)
	}
}

func TestSolveLZSSTornedText(t *testing.T) {
	// Moodle отдаёт тип записи тегом: «LZS S».
	q := "Сжать сообщение методом LZS S: КУСКУС Размер словаря - 10 символов, размер буфера - 6 символов."
	if _, ok := Solve(q); !ok {
		t.Fatal("не распознан LZSS в разорванном тегом тексте")
	}
}

func TestSolveHuffmanTrace(t *testing.T) {
	res, ok := Solve(qHuffman)
	if !ok {
		t.Fatal("решатель не взял трассу Хаффмана")
	}
	if res.Answer != "RTND" {
		t.Fatalf("ответ = %q, ждали RTND", res.Answer)
	}
}

func TestSolveIgnoresOrdinaryQuestion(t *testing.T) {
	if _, ok := Solve("Что такое пиксель? Выберите один ответ: a. точка b. формат"); ok {
		t.Fatal("решатель взялся за обычный теоретический вопрос")
	}
}

func TestSolveLZ78EncodeCommaFormat(t *testing.T) {
	q := "Сжать сообщение алгоритмом LZ78: МУМУМУ_МУКА_МУРКА Размер словаря - 32 записи. Формат одной записи: [число,буква]. Запишите ответ заглавными русскими буквами и цифрами без пробелов между записями."
	res, ok := Solve(q)
	if !ok {
		t.Fatal("решатель не взял LZ78 на сжатие")
	}
	if !reRecordComma.MatchString(q) {
		t.Fatal("не распознан формат записи с запятой")
	}
	// Обратная проверка: код должен раскодироваться в исходное сообщение.
	msg, ok := DecodeLZ78(res.Answer, 32)
	if !ok || msg != "МУМУМУ_МУКА_МУРКА" {
		t.Fatalf("обратное декодирование %q дало %q (ok=%t)", res.Answer, msg, ok)
	}
}
